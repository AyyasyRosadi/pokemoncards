/**
 * getTemplate — cari template berdasarkan id.
 * Task:
 * 1. Terima id template
 * 2. Cari di daftar TEMPLATES
 * 3. Kembalikan template, atau undefined jika tidak ada
 */
export function getTemplate(id: string): CardTemplate | undefined {
  return TEMPLATES.find((t) => t.id === id);
}

/**
 * pickRandomTemplate — pilih satu template Pokémon secara acak.
 * Task:
 * 1. Buang template "blank" dan template yang sedang aktif dari kandidat
 * 2. Pilih satu secara acak
 * 3. Kembalikan id-nya
 */
export function pickRandomTemplate(excludeId?: string | null): string {
  const pool = TEMPLATES.filter((t) => t.id !== "blank" && t.id !== excludeId);
  return pool[Math.floor(Math.random() * pool.length)].id;
}
