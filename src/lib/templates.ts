/**
 * define — buat satu template dari data Pokémon.
 * Task:
 * 1. Ambil tema elemen untuk ikon dan label
 * 2. Pakai nama Pokémon sebagai label template
 * 3. Buat tagline "Elemen · Stage"
 * 4. Kelompokkan template berdasarkan rarity
 */
function define(id: string, data: Partial<CardData> & Pick<CardData, "name" | "element" | "rarity">): CardTemplate {
  const el = ELEMENTS[data.element];
  return {
    id,
    label: data.name,
    tagline: `${el.label} · ${data.stage ?? "BASIC"}`,
    icon: el.icon,
    group: data.rarity,
    data,
  };
}

